-- Run after converting assets. No native renderer or graphics libraries needed.
package.path="./?.lua;"..package.path
local cfg=require "config"
cfg.detail="fast"
cfg.cached_character=false
ui={btn=function() return false end,palset=function() end,camera=function() end,
clip=function() end,cls=function() end,rectfill=function() end,print=function() end,trisfill=function() end}
require "main"
Game.profile_mode=2
local angles,poses=64,16
local xbase,ybase,zbase=184,64,144
local lookup,data,seen={},{},{}
local triangles={}
Game.capture_triangle=function(t)
    local function x(v) assert(v>=xbase and v<=xbase+255,"character X exceeds packed range"); return v-xbase end
    local depth=math.floor(t[8]*32+0.5)-zbase
    assert(depth>=0 and depth<=255,"character depth exceeds packed range")
    assert(t[2]>=ybase and t[4]>=ybase and t[6]>=ybase,"character Y exceeds packed range")
    triangles[#triangles+1]=string.char(x(t[1]),t[2]-ybase,x(t[3]),t[4]-ybase,x(t[5]),t[6]-ybase,t[7],depth)
end
local maxTriangles=0
for direction=0,angles-1 do
    for pose=0,poses-1 do
        Game.facing=direction*math.pi*2/angles
        Game.phase=pose*math.pi*2/poses
        triangles={}
        Game.draw()
        local packed=table.concat(triangles)
        maxTriangles=math.max(maxTriangles,#packed/8)
        assert(#packed%8==0)
        if not seen[packed] then data[#data+1]=packed; seen[packed]=#data end
        lookup[#lookup+1]=seen[packed]
    end
end
local out=assert(io.open("character_frames.lua","wb"))
local function fingerprint(path)
    local file=assert(io.open(path,"rb")); local bytes=file:read("*a"):gsub("\r\n","\n");file:close()
    local hash=2166136261
    for i=1,#bytes do hash=((hash ~ bytes:byte(i))*16777619)&0xffffffff end
    return string.format("%08x",hash)
end
out:write("-- Generated by .tools/bake-character.lua from KayKit CC0 geometry.\n")
out:write("-- Packed screen coordinates, palette index and 1/32-unit depth.\n")
out:write('return {model_hash="',fingerprint("models.lua"),'",renderer_hash="',fingerprint("main.lua"),'",angles=',angles,",poses=",poses,",xbase=",xbase,",ybase=",ybase,",zbase=",zbase,",lookup={",table.concat(lookup,","),"},data={\n")
local bytes=0
for _,packed in ipairs(data) do
    out:write('"')
    for i=1,#packed do
        local b=string.byte(packed,i)
        if b==34 or b==92 then out:write("\\",string.char(b))
        elseif b>=32 and b<=126 then out:write(string.char(b))
        else out:write(string.format("\\%03d",b)) end
    end
    out:write('",\n')
    bytes=bytes+#packed
end
out:write("}}\n");out:close()
print(string.format("Baked %d directions x %d poses; %d unique frames; %d packed bytes; maximum %d triangles",angles,poses,#data,bytes,maxTriangles))
