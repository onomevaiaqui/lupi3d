// Node.js, no dependencies. Quantized vertex clustering, not random face removal.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = path.join(root, '.assets-source');
const models = {};
function compact(vertices, faces, cell) {
  const map = new Map(), v = [], f = [], seen = new Set();
  const indices = vertices.map(p => {
    const key = p.slice(0,3).map(x => Math.round(x/cell)).join(',')+','+p[3];
    if (!map.has(key)) { map.set(key,v.length/4+1); v.push(...p.map(x=>+x.toFixed(3))); }
    return map.get(key);
  });
  for(const face of faces) {
    const ids = face.slice(0,3).map(i=>indices[i]);
    if(new Set(ids).size<3) continue;
    const key = [...ids].sort((a,b)=>a-b).join(',');
    if(seen.has(key)) continue;
    const p=ids.map(i=>v.slice((i-1)*4,(i-1)*4+3));
    const a=p[1].map((x,i)=>x-p[0][i]),b=p[2].map((x,i)=>x-p[0][i]);
    const normal=[a[1]*b[2]-a[2]*b[1],a[2]*b[0]-a[0]*b[2],a[0]*b[1]-a[1]*b[0]];
    const length=Math.hypot(...normal);
    if(length<0.00001) continue;
    const light=(-normal[0]*0.4+normal[1]*0.8-normal[2]*0.45)/length;
    seen.add(key); f.push(...ids,face[3]+(light<0.2?16:0));
  }
  return {v,f};
}
function obj(file,kind) {
  const v=[],f=[];
  for(const line of fs.readFileSync(path.join(source,file),'utf8').split(/\r?\n/)) {
    const a=line.trim().split(/\s+/);
    if(a[0]==='v') v.push([...a.slice(1,4).map(Number),0]);
    if(a[0]==='f') {
      const ids=a.slice(1).map(s=>Number(s.split('/')[0])-1);
      for(let i=1;i<ids.length-1;i++) {
        const tri=[ids[0],ids[i],ids[i+1]];
        const y=tri.reduce((s,n)=>s+v[n][1],0)/3;
        f.push([...tri,kind==='tree'?(y<0.85?6:7):9]);
      }
    }
  }
  return compact(v,f,kind==='tree'?0.45:0.06);
}
const b=fs.readFileSync(path.join(source,'Knight.glb'));
const len=b.readUInt32LE(12), j=JSON.parse(b.subarray(20,20+len));
const bin=b.subarray(28+len);
function accessor(id) {
  const a=j.accessors[id],bv=j.bufferViews[a.bufferView];
  const size={SCALAR:1,VEC2:2,VEC3:3,VEC4:4}[a.type];
  const bytes={5126:4,5125:4,5123:2,5121:1}[a.componentType];
  const read={5126:'readFloatLE',5125:'readUInt32LE',5123:'readUInt16LE',5121:'readUInt8'}[a.componentType];
  return Array.from({length:a.count},(_,i)=>Array.from({length:size},(_,k)=>bin[read]((bv.byteOffset||0)+(a.byteOffset||0)+i*(bv.byteStride||bytes*size)+k*bytes)));
}
const v=[],f=[];
for(const mesh of j.meshes) {
  if(mesh.name==='Knight_Head'||mesh.name==='Knight_Cape') continue;
  let group=0,color=12;
  if(mesh.name.includes('LegLeft')) group=1;
  if(mesh.name.includes('LegRight')) group=2;
  if(mesh.name.includes('ArmLeft')) group=3;
  if(mesh.name.includes('ArmRight')) group=4;
  if(mesh.name.includes('Body')) color=14;
  if(mesh.name.includes('Visor')) color=11;
  for(const p of mesh.primitives) {
    const base=v.length;
    for(let xyz of accessor(p.attributes.POSITION)) {
      let [x,y,z]=xyz;
      // Lower the source T-pose arms to a relaxed walking pose.
      if(group===3||group===4) {
        const side=group===3?1:-1, a=-side*1.15;
        const dx=x-side*0.25,dy=y-1.15;
        x=side*0.25+dx*Math.cos(a)-dy*Math.sin(a);
        y=1.15+dx*Math.sin(a)+dy*Math.cos(a);
      }
      v.push([x,y,z,group]);
    }
    const ids=accessor(p.indices).flat();
    for(let i=0;i<ids.length;i+=3) f.push([base+ids[i],base+ids[i+1],base+ids[i+2],color]);
  }
}
models.knight=compact(v,f,0.19);
