// Offline only. meshoptimizer 1.3.0 (MIT) preserves the source surface.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),source=path.join(root,'.assets-source');
const round=x=>+x.toFixed(5);
async function main() {
  const {MeshoptSimplifier:s}=await import('./vendor/meshopt_simplifier.mjs');
  await s.ready;
  function reduce(vertices,triangles,target,error) {
    // Weld exact duplicates only. Grid clustering can open holes at joints.
    const map=new Map(),v=[],ids=vertices.map(p=>{
      const key=p.map(round).join(',');
      if(!map.has(key)) {map.set(key,v.length);v.push(p.map(round));}
      return map.get(key);
    });
    const indices=new Uint32Array(triangles.flatMap(t=>t.map(i=>ids[i])));
    const positions=new Float32Array(v.flatMap(p=>p.slice(0,3)));
    const [result]=s.simplify(indices,positions,3,target*3,error,['Permissive']);
    const used=new Map(),out={v:[],f:[]};
    for(let i=0;i<result.length;i+=3) {
      for(let k=0;k<3;k++) {
        const id=result[i+k];
        if(!used.has(id)) {used.set(id,out.v.length/4+1);out.v.push(...v[id]);}
        out.f.push(used.get(id));
      }
    }
    return out;
  }
  function colored(part,colorForFace) {
    const f=[];
    for(let i=0;i<part.f.length;i+=3) {
      const ids=part.f.slice(i,i+3),p=ids.map(id=>part.v.slice((id-1)*4,(id-1)*4+3));
      const a=p[1].map((x,k)=>x-p[0][k]),b=p[2].map((x,k)=>x-p[0][k]);
      const n=[a[1]*b[2]-a[2]*b[1],a[2]*b[0]-a[0]*b[2],a[0]*b[1]-a[1]*b[0]];
      assert(Math.hypot(...n)>1e-9,'degenerate triangle');
      const light=(-n[0]*0.4+n[1]*0.8-n[2]*0.45)/Math.hypot(...n);
      f.push(...ids,colorForFace(p)+(light<0.2?16:0));
    }
    return {v:part.v,f};
  }
  function obj(file,kind,target) {
    const v=[],f=[];
    for(const line of fs.readFileSync(path.join(source,file),'utf8').split(/\r?\n/)) {
      const a=line.trim().split(/\s+/);
      if(a[0]==='v') v.push([...a.slice(1,4).map(Number),0]);
      if(a[0]==='f') {
        const ids=a.slice(1).map(s=>Number(s.split('/')[0])-1);
        for(let i=1;i<ids.length-1;i++) f.push([ids[0],ids[i],ids[i+1]]);
      }
    }
    return colored(reduce(v,f,target,0.035),p=>kind==='tree'?(p.reduce((s,v)=>s+v[1],0)/3<0.85?6:7):9);
  }
  const b=fs.readFileSync(path.join(source,'Knight.glb')),len=b.readUInt32LE(12);
  const j=JSON.parse(b.subarray(20,20+len)),bin=b.subarray(28+len);
  function accessor(id) {
    const a=j.accessors[id],bv=j.bufferViews[a.bufferView];
    const size={SCALAR:1,VEC2:2,VEC3:3,VEC4:4}[a.type];
    const bytes={5126:4,5125:4,5123:2,5121:1}[a.componentType];
    const read={5126:'readFloatLE',5125:'readUInt32LE',5123:'readUInt16LE',5121:'readUInt8'}[a.componentType];
    return Array.from({length:a.count},(_,i)=>Array.from({length:size},(_,k)=>bin[read]((bv.byteOffset||0)+(a.byteOffset||0)+i*(bv.byteStride||bytes*size)+k*bytes)));
  }
  const knight={v:[],f:[]},parts=[];
  for(const mesh of j.meshes) {
    if(mesh.name==='Knight_Cape') continue;
    const name=mesh.name;
    const group=name.includes('LegLeft')?1:name.includes('LegRight')?2:name.includes('ArmLeft')?3:name.includes('ArmRight')?4:0;
    const color=name.includes('Body')?14:name.includes('Head')?5:12;
    const target=group?28:name.includes('Body')?68:name.includes('Head')?48:name.includes('Visor')?32:72;
    const v=[],f=[];
    for(const p of mesh.primitives) {
      const base=v.length;
      for(let [x,y,z] of accessor(p.attributes.POSITION)) {
        if(group===3||group===4) {
          const side=group===3?1:-1,a=-side*1.15,dx=x-side*0.25,dy=y-1.15;
          x=side*0.25+dx*Math.cos(a)-dy*Math.sin(a);y=1.15+dx*Math.sin(a)+dy*Math.cos(a);
        }
        v.push([x,y,z,group]);
      }
      const ids=accessor(p.indices).flat();
      for(let i=0;i<ids.length;i+=3) f.push([base+ids[i],base+ids[i+1],base+ids[i+2]]);
    }
    const part=colored(reduce(v,f,target,0.075),()=>color),offset=knight.v.length/4;
    const start=knight.v.length/4+1;
    knight.v.push(...part.v);
    for(let i=0;i<part.f.length;i+=4) knight.f.push(part.f[i]+offset,part.f[i+1]+offset,part.f[i+2]+offset,part.f[i+3]);
    parts.push({name,group,start,end:knight.v.length/4,faces:part.f.length/4});
  }
  const models={knight,tree:obj('Tree_1_A_Color1.obj','tree',70),rock:obj('Rock_1_A_Color1.obj','rock',24)};
  let out='-- Generated by .tools/convert-assets.cjs. KayKit CC0, see CREDITS.md.\nreturn {\n';
  for(const [name,m] of Object.entries(models)) {
    out+=`${name}={v={${m.v.join(',')}},f={${m.f.join(',')}}},\n`;
    console.log(name,m.v.length/4,'vertices',m.f.length/4,'triangles');
  }
  fs.writeFileSync(path.join(root,'models.lua'),out+'}\n');
  fs.writeFileSync(path.join(__dirname,'model-parts.json'),JSON.stringify(parts,null,2)+'\n');
}
main().catch(e=>{console.error(e);process.exitCode=1;});
